#!/bin/bash
# FrameShift stage 3d — offline provenance and re-check of the stock v2.7 inputs (run inside WSL):
#   wsl.exe -e bash <repo>/devices/quest3/stage3d/tools/v27-inputs.sh
# Read-only on the firmware area; no device, no network. Writes the tracked reports in stage3d/provenance/:
#   ota.txt        the OTA zip hash, its metadata, payload.bin new_partition_info for every partition, and the
#                  extracted boot/vendor_boot/vbmeta/vbmeta_system/dtbo checked against it (tools/ota-payload-check.py)
#   avb.txt        the vbmeta digest computed from vbmeta + vbmeta_system (= Unit 2's runtime ro.boot.vbmeta.digest)
#                  and the boot / vendor_boot / dtbo hash descriptors (tools/avb-check.py)
#   runtime.txt    the matching runtime facts from Unit 2's read-only baseline (kernel release, build, vendor
#                  command line, bootconfig-derived properties, dtb/dtbo indexes; no serial number)
#   images.txt     boot / vendor_boot headers v66 vs v2.7, kernel release strings, vendor bootconfig, ramdisk lists
#   modules.txt    modules.load.recovery v66 vs v2.7 (order, additions, removals), vermagic, softdeps, and the
#                  dependency closure of the display / USB / backlight / LED / fan modules (tools/module-closure.py)
#   dt.txt         the dtbo index of both builds, the overlay the unit's ABL chose (v66 Unit 1 idx 10, v2.7 Unit 2
#                  idx 11), and the raw-property differences of the display, DSI and USB nodes of the merged DTs
#                  (tools/dt-props-compare.py), plus the SDE catalog values the stage-3c layout depends on
set -euo pipefail
ROOT="$(cd "$(dirname "$(readlink -f "$0")")/../../../.." && pwd)"
Q3=$ROOT/devices/quest3
HERE=$Q3/stage3d
T=$HERE/tools
P=$HERE/provenance
AOSP=$ROOT/build/third_party/mkbootimg
F27=$ROOT/firmware/quest3/v2.7-user_ota
F66=$ROOT/firmware/quest3/v66_unit1_slotA
ZIP=$ROOT/firmware/quest3/ota/q3_52433670036000520.zip
EV=$Q3/evidence/unit2-v27-baseline-20261012
W=$(mktemp -d); trap 'rm -rf "$W"' EXIT
mkdir -p "$P"
for t in python3 lz4 cpio dtc fdtoverlay strings sha256sum; do command -v $t >/dev/null || { echo "missing $t"; exit 2; }; done
export PYTHONDONTWRITEBYTECODE=1
stamp="# generated by stage3d/tools/v27-inputs.sh $(sha256sum "$0" | cut -c1-16) (offline, read-only)"

# ---- ota.txt -------------------------------------------------------------------------------------------
{ echo "$stamp"; echo "zip: $(sha256sum "$ZIP" | cut -c1-64)  firmware/quest3/ota/q3_52433670036000520.zip ($(stat -c %s "$ZIP") B)"
  python3 -I "$T/ota-payload-check.py" "$ZIP" boot="$F27/boot.img" vendor_boot="$F27/vendor_boot.img" vbmeta="$F27/vbmeta.img" \
      vbmeta_system="$F27/vbmeta_system.img" dtbo="$F27/dtbo.img" | sed "s#$ROOT/##g"; } > "$P/ota.txt"

# ---- avb.txt -------------------------------------------------------------------------------------------
{ echo "$stamp"
  python3 -I "$T/avb-check.py" --vbmeta "$F27/vbmeta.img" --chain vbmeta_system="$F27/vbmeta_system.img" \
      --hash boot="$F27/boot.img" --hash vendor_boot="$F27/vendor_boot.img" --hash dtbo="$F27/dtbo.img" \
      --expect-digest 66b7619671a8a8dcb75262812e7ce1bd176af6aa32cd76dc3548b9c942e9f12a | sed "s#$ROOT/##g"; } > "$P/avb.txt"

# ---- unpack ---------------------------------------------------------------------------------------------
for v in v66:$F66 v27:$F27; do
    t=${v%%:*}; d=${v#*:}
    python3 -E -s -B "$AOSP/unpack_bootimg.py" --boot_img "$d/boot.img" --out "$W/$t-boot" > "$W/$t-boot.txt"
    python3 -E -s -B "$AOSP/unpack_bootimg.py" --boot_img "$d/vendor_boot.img" --out "$W/$t-vboot" > "$W/$t-vboot.txt"
    mkdir -p "$W/$t-vx"; (cd "$W/$t-vx" && lz4 -dc "$W/$t-vboot/vendor_ramdisk00" | cpio -id --quiet --no-absolute-filenames)
    (cd "$W/$t-vx" && find . -mindepth 1 | sed 's#^\./##' | LC_ALL=C sort) > "$W/$t.list"
done

# ---- runtime.txt (Unit 2, read-only baseline 2026-10-12; no serial number) ----------------------------------
{ echo "$stamp"; echo "source: devices/quest3/evidence/unit2-v27-baseline-20261012 (read-only adb, J-115)"
  grep -h '^Linux version' "$EV/proc-version.txt" || true
  grep -E '^\[(ro\.build\.fingerprint|ro\.build\.version\.incremental|ro\.build\.type|ro\.bootimage\.build\.date\.utc|ro\.boot\.vbmeta\.(digest|size|hash_alg)|ro\.boot\.slot_suffix|ro\.boot\.dtb_idx|ro\.boot\.dtbo_idx|ro\.boot\.load_modules_parallel|ro\.boot\.usbcontroller|ro\.boot\.hardware|ro\.boot\.verifiedbootstate|ro\.boot\.bootreason)\]' "$EV/getprop-all.txt"
  echo "/proc/cmdline vendor part (compare with the v2.7 vendor_boot 'vendor command line args' in images.txt):"
  grep -v '^#' "$EV/proc-cmdline.txt" | grep -o 'video=vfb[^ ]*.* bootconfig' || true
  echo "panel chosen at run time: $(grep -v '^#' "$EV/proc-cmdline.txt" | grep -o 'msm_drm.dsi_display0=[^ ]*' || true)"; } > "$P/runtime.txt"

# ---- images.txt -------------------------------------------------------------------------------------------
{ echo "$stamp"
  for t in v66 v27; do
      echo "== $t boot header"; cat "$W/$t-boot.txt"
      echo "== $t kernel: sha256 $(sha256sum "$W/$t-boot/kernel" | cut -c1-64); $(grep -aoE 'Linux version 5\.10[ -~]{0,110}' "$W/$t-boot/kernel" | head -1)"
      echo "== $t vendor_boot header"; cat "$W/$t-vboot.txt"
      echo "== $t vendor bootconfig"; cat "$W/$t-vboot/bootconfig"; echo
      echo "== $t vendor ramdisk: $(wc -l < "$W/$t.list") entries, list sha256 $(sha256sum "$W/$t.list" | cut -c1-64); ELF executables: $(cd "$W/$t-vx" && find . -type f -print0 | xargs -0 file | grep -cE 'ELF .*(executable|shared object)' || true)"
  done
  echo "== vendor ramdisk path list, v66 (<) vs v2.7 (>)"; diff "$W/v66.list" "$W/v27.list" || true; } > "$P/images.txt"

# ---- modules.txt -------------------------------------------------------------------------------------------
M66=$W/v66-vx/lib/modules; M27=$W/v27-vx/lib/modules
{ echo "$stamp"
  for t in v66 v27; do M=$W/$t-vx/lib/modules
      echo "== $t: modules.load.recovery $(wc -l < "$M/modules.load.recovery") entries sha256 $(sha256sum "$M/modules.load.recovery" | cut -c1-64); modules.load $(wc -l < "$M/modules.load"); .ko files $(ls "$M"/*.ko | wc -l); load == load.recovery: $(cmp -s "$M/modules.load" "$M/modules.load.recovery" && echo yes || echo no)"
      echo "   vermagic: $(for k in "$M"/*.ko; do strings -a "$k" | grep -m1 '^vermagic='; done | sort | uniq -c | tr -s ' ' | tr '\n' ';')"
  done
  echo "== added in v2.7 (not in the v66 recovery list):"; comm -13 <(sort "$M66/modules.load.recovery") <(sort "$M27/modules.load.recovery") | tr '\n' ' '; echo
  echo "== removed in v2.7:"; comm -23 <(sort "$M66/modules.load.recovery") <(sort "$M27/modules.load.recovery") | tr '\n' ' '; echo
  echo "== v2.7 vendor load order (for reference only: stage 3d does NOT load it; init.sh loads stage3d/modules.load.v66, J-129):"
  cat -n "$M27/modules.load.recovery" | tr -s ' \t' ' ' | tr '\n' ';'; echo
  echo "== modules.softdep v66 (<) vs v2.7 (>)"; diff "$M66/modules.softdep" "$M27/modules.softdep" || true
  echo "== closure of the display / USB / backlight / LED / fan roots (symbol + softdep; platform probe dependencies not modelled)"
  python3 -I "$T/module-closure.py" - msm_drm,dwc3-msm,leds-qti-tri-led,tps65132-regulator,blu_fw_driver,mp3314,pwm-qti-lpg,msm_ext_display,panel_event_notifier,dispcc0-anorak,dispcc1-anorak,ucsi_glink,pwm-tach-fan "$M66" "$M27" | sed "s#$W/##g"
  echo "== the list stage 3d LOADS (PM decision J-129): stage3d/modules.load.v66 = the v66 list minus debug-regulator, qti-regmap-debugfs"
  echo "   sha256 $(sha256sum "$HERE/modules.load.v66" | cut -c1-64); $(wc -l < "$HERE/modules.load.v66") entries; equal to the v66 list minus the two: $(cmp -s <(grep -vxE 'debug-regulator.ko|qti-regmap-debugfs.ko' "$M66/modules.load.recovery") "$HERE/modules.load.v66" && echo yes || echo NO)"
  python3 -I "$T/module-list-check.py" "$HERE/modules.load.v66" "$M27" msm_drm,dwc3-msm,leds-qti-tri-led,tps65132-regulator,blu_fw_driver,mp3314,pwm-qti-lpg,msm_ext_display,panel_event_notifier,dispcc0-anorak,dispcc1-anorak,ucsi_glink,pwm-tach-fan
  echo "   vendor index pinned in init.sh: modules.dep $(sha256sum "$M27/modules.dep" | cut -c1-64), modules.softdep $(sha256sum "$M27/modules.softdep" | cut -c1-64)"; } > "$P/modules.txt"

# ---- dt.txt ---------------------------------------------------------------------------------------------------
mkdir -p "$W/dt"
python3 -I - "$F66/dtbo.img" "$F27/dtbo.img" "$W/dt" > "$W/dtbo-index.txt" <<'PY'
import hashlib, struct, sys
for tag, p in (("v66", sys.argv[1]), ("v27", sys.argv[2])):
    d = open(p, "rb").read()
    magic, total, hsz, esz, cnt, off, pg, ver = struct.unpack(">8I", d[:32])
    assert magic == 0xd7b7ab1e
    print("%s dtbo.img sha256 %s: %d entries" % (tag, hashlib.sha256(d).hexdigest(), cnt))
    for k in range(cnt):
        sz, o, i, r = struct.unpack(">4I", d[off + k * esz:off + k * esz + 16])
        open("%s/%s-dtbo%02d.dtb" % (sys.argv[3], tag, k), "wb").write(d[o:o + sz])
PY
cp "$W/v66-vboot/dtb" "$W/dt/v66-base.dtb"; cp "$W/v27-vboot/dtb" "$W/dt/v27-base.dtb"
fdtoverlay -i "$W/dt/v66-base.dtb" -o "$W/dt/v66-merged.dtb" "$W/dt/v66-dtbo10.dtb"
fdtoverlay -i "$W/dt/v27-base.dtb" -o "$W/dt/v27-merged.dtb" "$W/dt/v27-dtbo11.dtb"
dtc -q -I dtb -O dts -o "$W/dt/v27-merged.dts" "$W/dt/v27-merged.dtb"
PNL=/soc/qcom,mdss_mdp@ae00000
{ echo "$stamp"; cat "$W/dtbo-index.txt"
  for f in "$W"/dt/v*-dtbo*.dtb; do b=$(basename "$f" .dtb); dtc -q -I dtb -O dts -o "$W/dt/$b.dts" "$f"
      echo "$b: $(grep -m1 'model =' "$W/dt/$b.dts" | tr -d '\t') | $(grep -m1 'qcom,board-id' "$W/dt/$b.dts" | tr -d '\t') | sha256 $(sha256sum "$f" | cut -c1-16)"; done
  echo "base dtb: v66 $(sha256sum "$W/dt/v66-base.dtb" | cut -c1-64); v2.7 $(sha256sum "$W/dt/v27-base.dtb" | cut -c1-64)"
  echo "chosen overlays (ro.boot.dtbo_idx): v66 Unit 1 = 10, v2.7 Unit 2 = 11; byte-identical: $(cmp -s "$W/dt/v66-dtbo10.dtb" "$W/dt/v27-dtbo11.dtb" && echo yes || echo no)"
  echo "== raw property differences, merged v66 (A) vs merged v2.7 (B)"
  python3 -I "$T/dt-props-compare.py" "$W/dt/v66-merged.dtb" "$W/dt/v27-merged.dtb" "$PNL" "$PNL/meta,eureka_panel_sharp" \
      "$PNL/meta,eureka_panel_sharp/qcom,mdss-dsi-display-timings/timing@0" "$PNL/meta,eureka_panel_sharp/qcom,mdss-dsi-display-timings/timing@1" \
      /soc/qcom,dsi-display-primary /soc/qcom,mdss_mdp0_dsi_ctrl0@ae94000 /soc/qcom,mdss_mdp0_dsi_ctrl1@ae96000 \
      /soc/qcom,mdss_mdp0_dsi_phy0@ae95500 /soc/qcom,mdss_mdp0_dsi_phy1@ae97500 /soc/dsi_panel_pwr_supply_eureka \
      /soc/ssusb@a600000 /soc/ssusb@a600000/dwc3@a600000 /soc/qcom,sde_rscc@af20000
  echo "== v2.7 merged DT: the values the stage-3c layout depends on"
  echo "-- qcom,mdss_mdp@ae00000 (its own properties, up to its first child node)"
  awk '/qcom,mdss_mdp@ae00000 \{/{f=1; next} f&&/\{$/{exit} f' "$W/dt/v27-merged.dts" | grep -E 'clock-max-rate|qcom,sde-mixer-blendstages|qcom,sde-mixer-linewidth|qcom,sde-sspp-linewidth|qcom,sde-sspp-type|qcom,sde-sspp-smart-dma-priority|qcom,sde-pipe-order-version|qcom,sde-max-bw-high-kbps|meta,swap-mixers|meta,freerun-histogram' | tr -d '\t'
  echo "-- meta,eureka_panel_sharp (orientation) and its timing@0"
  awk '/meta,eureka_panel_sharp \{/{f=1} f&&/qcom,mdss-dsi-panel-orientation/{print; exit}' "$W/dt/v27-merged.dts" | tr -d '\t'
  awk '/meta,eureka_panel_sharp \{/{f=1} f&&/timing@0 \{/{g=1} g&&/timing@1 \{/{exit} g' "$W/dt/v27-merged.dts" | grep -E 'qcom,mdss-dsi-(panel-width|panel-height|panel-framerate|h-front-porch|h-back-porch|h-pulse-width|v-back-porch|v-front-porch|v-pulse-width)|qcom,display-topology|qcom,compression-mode|qcom,mdss-dsc-|qcom,disable-default-pps' | tr -d '\t'
  grep -E 'meta,swap-mixers' "$W/dt/v27-merged.dts" >/dev/null && echo "meta,swap-mixers: PRESENT" || echo "meta,swap-mixers: absent"; } > "$P/dt.txt"
( cd "$P" && sha256sum ota.txt avb.txt runtime.txt images.txt modules.txt dt.txt > SHA256SUMS )
cat "$P/SHA256SUMS"
