"""Decode an fs-metacfg record (METACFG-SPEC §6) and print a derived table.

The derived table holds identifiers and thresholds only (allowed per J-123):
the row identity (device, vendor incremental, sha256 of the JSON and of the
VR-runtime list, the parse digest) and one line per sensor with its
multiplier, seven HotThreshold slots and seven HotHysteresis slots in
milli-units ('-' = unset). It never contains file bytes.

usage: mcrec.py RECORD [--derived] [--label LABEL]
"""
import hashlib
import struct
import sys

UNSET = -0x80000000
NAMES = {0: 'ok'}
_codes = ("arg no-super super-ambiguous super-type super-size slot seccomp io read-budget "
          "lp-geometry lp-header lp-checksum lp-tables lp-blockdev lp-name vab-merge no-vendor "
          "vendor-dup vendor-disabled extent-type fs-type ext4-blocksize ext4-features "
          "ext4-inode-size ext4-geometry ext4-size ext4-inode ext4-range ext4-inode-flags "
          "ext4-isize ext4-extent-magic ext4-extent-count ext4-extent-depth ext4-uninit ext4-hole "
          "ext4-notdir ext4-dirent ext4-dir-cap file-missing file-type file-size buildprop "
          "json-syntax json-depth json-dupkey json-unknown-key json-number json-vr json-monitor "
          "json-name json-dupname json-count json-slots json-type extent-source extent-range "
          "vab-device lp-flags vab-cow-group overlay vab-updated lp-attr vab-policy").split()
for i, n in enumerate(_codes, 1):
    NAMES[i] = n


def decode(b):
    if len(b) < 64 or b[:4] != b'FSMC':
        raise ValueError('bad record')
    ver, st, jl, vl, dl, il, n, es, lpf, vat, slot, fl = struct.unpack_from('<HHIIHHIIIIII', b, 4)
    r = {'version': ver, 'status': NAMES.get(st, str(st)), 'json_len': jl, 'vr_len': vl, 'n': n,
         'entry_size': es, 'lp_flags': lpf, 'vendor_attr': vat, 'slot': slot, 'flags': fl}
    p = 64
    r['json'] = b[p:p + jl]; p += jl
    r['vr'] = b[p:p + vl]; p += vl
    r['dev'] = b[p:p + dl].decode(); p += dl
    r['incr'] = b[p:p + il].decode(); p += il
    ents = b[p:p + n * 96]
    r['entries_raw'] = ents
    r['entries'] = []
    for k in range(n):
        e = ents[96 * k:96 * (k + 1)]
        name = e[:32].rstrip(b'\0').decode()
        v = struct.unpack_from('<14i2i', e, 32)
        r['entries'].append((name, list(v[0:7]), list(v[7:14]), v[14], v[15]))
    r['trailing'] = len(b) - (p + n * 96)
    return r


def fmt(v):
    return '-' if v == UNSET else str(v)


def main():
    b = open(sys.argv[1], 'rb').read()
    r = decode(b)
    label = sys.argv[sys.argv.index('--label') + 1] if '--label' in sys.argv else ''
    if '--derived' not in sys.argv:
        print(f"status={r['status']} json={r['json_len']} vr={r['vr_len']} n={r['n']} slot={r['slot']} "
              f"flags={r['flags']:#x} lpflags={r['lp_flags']:#x} vattr={r['vendor_attr']:#x}")
        if r['status'] == 'ok':
            print('digest', hashlib.sha256(r['entries_raw']).hexdigest())
        return
    if r['status'] != 'ok':
        sys.exit(f"record status {r['status']}")
    print(f"# derived table {label}: identifiers and thresholds only (J-123); generated by tools/mcrec.py")
    print(f"#device\t{r['dev']}")
    print(f"#incremental\t{r['incr']}")
    print(f"#json_sha256\t{hashlib.sha256(r['json']).hexdigest()}")
    print(f"#json_size\t{r['json_len']}")
    print(f"#vr_sha256\t{hashlib.sha256(r['vr']).hexdigest()}")
    print(f"#digest\t{hashlib.sha256(r['entries_raw']).hexdigest()}")
    print("name\tmult\tslot0\tslot1\tslot2\tslot3\tslot4\tslot5\tslot6\thy0\thy1\thy2\thy3\thy4\thy5\thy6")
    for name, sl, hy, mn, md in r['entries']:
        print('\t'.join([name, f'{mn}/{md}'] + [fmt(x) for x in sl] + [fmt(x) for x in hy]))


if __name__ == '__main__':
    main()
