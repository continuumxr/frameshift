static const uint8_t *wglyph_rows(char ch)
{
	for (size_t i = 0; i < sizeof wfont / sizeof wfont[0]; i++)
		if (wfont[i].ch == ch)
			return wfont[i].row;
	return wfont[0].row; /* unknown: blank */
}

/* one eye: the lines centred inside the recovery margins (the visible lens area) */
static void warn_draw_eye(struct canvas *c, int left)
{
	int64_t ew = c->ew, h = c->h;
	int64_t mx = ew * FSP_MARGIN_X / FSP_EYE_W;
	int64_t u = (ew - 2 * mx) / (6 * WARN_COLS);
	int64_t lh, n = 0, y0;
	(void)left; /* the same text in both eyes; blit_eye applies each eye's roll */
	if (u < 2)
		u = 2;
	lh = 11 * u;
	for (int i = 0; i < WARN_LINES; i++)
		if (g_warn[i][0])
			n = i + 1;
	y0 = h / 2 - (n * lh) / 2;
	for (int i = 0; i < n; i++) {
		int64_t len = (int64_t)strlen(g_warn[i]);
		int64_t tw = len * 6 * u - u;
		int64_t tx = ew / 2 - tw / 2, ty = y0 + i * lh;
		for (int64_t k = 0; k < len; k++) {
			const uint8_t *g = wglyph_rows(g_warn[i][k]);
			for (int r = 0; r < 7; r++)
				for (int col = 0; col < 5; col++)
					if (g[r] & (0x10 >> col))
						rect(c, tx + k * 6 * u + col * u, ty + r * u, tx + k * 6 * u + (col + 1) * u,
						     ty + (r + 1) * u, C_TEXT);
		}
		if (i == 0) /* underline the headline */
			rect(c, tx, ty + 8 * u, tx + tw, ty + 8 * u + u / 2 + 1, C_TEXT);
	}
}
